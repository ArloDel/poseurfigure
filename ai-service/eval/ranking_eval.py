"""Compare recommendation ranking v1 ("score") with v2 ("hybrid") and write reports/ranking_v2.md.

usage (from ai-service/):  python -m eval.ranking_eval

On eval_v1 figures with hand-labeled keypoints, each strategy ranks the catalog twice: from the labeled
keypoints and from the model's predicted keypoints. A good ranking gives the user the same suggestions
either way (stable) and a varied list (diverse).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from PIL import Image

from app.config import get_settings
from app.schemas.analysis import RecommendRequest
from app.services.pose_extractor import build_pose
from app.services.pose_matcher import match, to_view
from app.services.profiles import load_profiles
from app.services.recommender import DUPLICATE, rank

ROOT = Path(__file__).resolve().parents[2]
STRATEGIES = ("score", "hybrid")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    from app.main import build_pipeline

    profiles = load_profiles(get_settings().skeleton_profiles_path)
    pipe = build_pipeline()
    catalog = [p for p in json.loads((ROOT / "shared/catalog/poses.json").read_text(encoding="utf-8"))["poses"] if p["published"]]
    ids = {i: p for i, p in enumerate(catalog, start=1)}
    ds = ROOT / "ai-service/datasets/eval_v1"
    ann = json.loads((ds / "annotations.json").read_text(encoding="utf-8"))

    def candidates(profile):
        return [{"id": i, "keypoints": p["keypoints"], "image_size": [p["image"]["width"], p["image"]["height"]],
                 "category": p["category"], "difficulty": p["difficulty"]} for i, p in ids.items() if p["profile"] == profile]

    def request(kps, size, profile):
        return RecommendRequest(profile=profile, pose={"keypoints": kps, "image_size": size}, candidates=candidates(profile), top_k=5)

    stats = {s: {"top1": 0, "overlap": 0.0, "categories": 0.0, "dup_lists": 0, "type_only": 0} for s in STRATEGIES}
    rows, n = [], 0
    vis = {2: "visible", 1: "uncertain", 0: "not_visible"}
    for img in ann["images"]:
        for g in img["figures"]:
            if "keypoints" not in g:
                continue
            im = Image.open(ds / "images" / img["file"]).convert("RGB")
            prof = profiles[g["profile"]]
            gt = {k: {"x": x if v else None, "y": y if v else None, "visibility": vis[v]} for k, (x, y, v) in g["keypoints"].items()}
            pose = build_pose(pipe.estimator.estimate(im, tuple(g["bbox"])), prof, im.size)
            pred = {k: {"x": p.x, "y": p.y, "visibility": p.visibility} for k, p in pose.keypoints.items()}
            n += 1
            row = [img["file"]]
            for s in STRATEGIES:
                a = rank(request(gt, list(im.size), g["profile"]), prof, s)
                b = rank(request(pred, list(im.size), g["profile"]), prof, s)
                ta, tb = [r.id for r in a.results], [r.id for r in b.results]
                st = stats[s]
                st["top1"] += ta[0] == tb[0]
                st["overlap"] += len(set(ta) & set(tb)) / len(ta)
                st["categories"] += len({ids[i]["category"] for i in tb})
                st["type_only"] += b.basis == "type_only"
                views = {i: to_view(json_points(ids[i]["keypoints"]), (ids[i]["image"]["width"], ids[i]["image"]["height"])) for i in tb}
                dup = any(match(views[x], views[y], prof).similarity >= DUPLICATE for k, x in enumerate(tb) for y in tb[k + 1:])
                st["dup_lists"] += dup
                row.append(" / ".join(ids[i]["slug"] for i in tb[:3]))
            rows.append(row)
            print(row[0], "|", row[1], "||", row[2])

    md = ["# Sprint 6 ranking evaluation", "", "Generated by `python -m eval.ranking_eval`.",
          f"{n} eval_v1 figures with hand-labeled keypoints; each strategy ranks the catalog from labeled and from predicted keypoints.", "",
          "| Measure | v1 score | v2 hybrid |", "|---|---:|---:|"]
    f = lambda key, fmt: " | ".join(fmt(stats[s][key]) for s in STRATEGIES)  # noqa: E731
    md += [f"| Same first pose, labeled vs predicted keypoints | {f('top1', lambda v: f'{v}/{n} ({100 * v / n:.0f}%)')} |",
           f"| Top-5 overlap, labeled vs predicted | {f('overlap', lambda v: f'{100 * v / n:.0f}%')} |",
           f"| Different categories in the top 5 (average) | {f('categories', lambda v: f'{v / n:.1f}')} |",
           f"| Lists with two near-identical poses | {f('dup_lists', lambda v: f'{v}/{n}')} |",
           f"| Fell back to type-only (pose unreadable) | {f('type_only', lambda v: f'{v}/{n}')} |", "",
           "## Top 3 per figure (from predicted keypoints)", "", "| Photo | v1 | v2 |", "|---|---|---|"]
    md += [f"| {r[0]} | {r[1]} | {r[2]} |" for r in rows]
    md += ["", "## Reading these numbers", "",
           f"- \"Near-identical\" uses the same threshold ({DUPLICATE}) that v2 suppresses, so v2's 0 is partly by construction;",
           "  the useful signal is how often v1 shows duplicates.",
           "- Stability improves but stays moderate: with 8-9 poses per type, a keypoint error can still swap the first pick.",
           "  A larger catalog and a figure-specific keypoint model are the real fixes.",
           "- Stability and variety are measured here; whether people like the suggestions needs user testing", ""]
    (ROOT / "ai-service/reports/ranking_v2.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    print("\n".join(md[:12]))


def json_points(kps: dict) -> dict:
    from app.schemas.analysis import PosePoint
    return {k: PosePoint(**v) for k, v in kps.items()}


if __name__ == "__main__":
    main()
